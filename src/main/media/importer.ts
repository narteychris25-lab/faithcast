import { nativeImage } from 'electron'
import { existsSync, readdirSync, statSync, writeFileSync, unlinkSync } from 'node:fs'
import { basename, extname, join } from 'node:path'
import type { MediaItem } from '@shared/types'
import type { Repos } from '../db/repos'
import { paths } from '../paths'
import { CONVERT_IMAGE_EXTENSIONS, mediaTypeFor } from './types'
import { log } from '../log'

export interface MediaImportResult {
  imported: number
  skipped: number
  errors: string[]
  ids: string[]
}

const MAX_FILES = 5000

/** Expand directories (one level of recursion per call, bounded) into files. */
function expand(input: string[], depth = 0): string[] {
  const out: string[] = []
  for (const p of input) {
    try {
      const st = statSync(p)
      if (st.isDirectory() && depth < 4) {
        out.push(...expand(readdirSync(p).filter((f) => !f.startsWith('.')).map((f) => join(p, f)), depth + 1))
      } else if (st.isFile()) out.push(p)
    } catch {
      /* unreadable path: skipped */
    }
    if (out.length > MAX_FILES) break
  }
  return out.slice(0, MAX_FILES)
}

/**
 * Register files in the media library. Files stay where they are (no copy)
 * except formats Chromium cannot render, which get a converted copy.
 */
export async function importMedia(repos: Repos, input: string[], folder = ''): Promise<MediaImportResult> {
  const result: MediaImportResult = { imported: 0, skipped: 0, errors: [], ids: [] }
  for (const file of expand(input)) {
    const ext = extname(file).slice(1).toLowerCase()
    const type = mediaTypeFor(ext)
    if (!type) {
      result.skipped++
      continue
    }
    try {
      let path = file
      if (type === 'image' && CONVERT_IMAGE_EXTENSIONS.includes(ext)) path = convertImage(file)
      const existing = repos.media.getByPath(path)
      if (existing) {
        result.skipped++
        result.ids.push(existing.id)
        continue
      }
      let width: number | null = null
      let height: number | null = null
      if (type === 'image' && ext !== 'svg') {
        const img = nativeImage.createFromPath(path)
        if (!img.isEmpty()) ({ width, height } = img.getSize())
      }
      const item = repos.media.insert({
        name: basename(file, extname(file)),
        type,
        path,
        size: statSync(path).size,
        width,
        height,
        folder
      })
      await makeThumbnail(repos, item)
      result.imported++
      result.ids.push(item.id)
    } catch (e) {
      log.warn('media import failed', file, e)
      result.errors.push(`${basename(file)}: ${e instanceof Error ? e.message : String(e)}`)
    }
  }
  return result
}

function convertImage(file: string): string {
  const img = nativeImage.createFromPath(file)
  // macOS decodes HEIC/TIFF through ImageIO; Windows has no built-in decoder Electron can use.
  if (img.isEmpty()) throw new Error(process.platform === 'darwin' ? 'Unsupported image format' : 'This format can only be imported on a Mac — save it as JPEG or PNG first')
  const out = join(paths.library(), `${basename(file, extname(file))}-${Date.now()}.jpg`)
  writeFileSync(out, img.toJPEG(92))
  return out
}

/** Thumbnail via macOS QuickLook / the Windows shell (handles images and most videos without FFmpeg). */
export async function makeThumbnail(repos: Repos, item: MediaItem): Promise<boolean> {
  if (item.type === 'audio') return false
  const out = join(paths.thumbnails(), `${item.id}.jpg`)
  try {
    let img: Electron.NativeImage
    if (item.type === 'image' && extname(item.path).toLowerCase() !== '.svg') {
      img = nativeImage.createFromPath(item.path)
      if (!img.isEmpty()) {
        const { width } = img.getSize()
        if (width > 480) img = img.resize({ width: 480, quality: 'good' })
      }
    } else {
      // QuickLook / the Windows shell decode MP4/MOV; for other formats they return
      // a generic file icon, so let the renderer capture a real frame instead.
      // Images they can't decode (e.g. GIF/WebP on Windows) also fall back to the renderer.
      if (!['.mp4', '.m4v', '.mov'].includes(extname(item.path).toLowerCase())) return false
      img = await nativeImage.createThumbnailFromPath(item.path, { width: 480, height: 480 })
    }
    if (img.isEmpty()) return false
    writeFileSync(out, img.toJPEG(80))
    repos.media.update(item.id, { hasThumbnail: true })
    return true
  } catch (e) {
    log.info('thumbnail unavailable', item.path, String(e))
    return false
  }
}

/** Store a thumbnail generated by the renderer (video frame capture fallback). */
export function saveThumbnailData(repos: Repos, id: string, jpeg: Buffer): void {
  writeFileSync(join(paths.thumbnails(), `${id}.jpg`), jpeg)
  repos.media.update(id, { hasThumbnail: true })
}

export function deleteThumbnail(id: string): void {
  const f = join(paths.thumbnails(), `${id}.jpg`)
  if (existsSync(f)) unlinkSync(f)
}

/** Flag media whose files have disappeared (or come back). */
export function checkMissing(repos: Repos): { checked: number; missing: string[] } {
  const missing: string[] = []
  const all = repos.media.allPaths()
  for (const m of all) {
    const gone = !existsSync(m.path)
    if (gone) missing.push(m.id)
    if (gone !== m.missing) repos.media.update(m.id, { missing: gone })
  }
  return { checked: all.length, missing }
}
